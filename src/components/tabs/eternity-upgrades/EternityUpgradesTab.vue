## 效果翻译

**Deepened Desolation（深化荒芜）**
> 解除虚物质上限，并使其以大幅降低的比率增强神性维度。
> 效果：基于虚物质提供神性维度幂次加成。

**Compressed Collections（压缩聚藏）**
> 基于星系的终局技能成本缩放大幅降低。

**Cubic Collapse（立方坍缩）**
> 瓦解莱特拉现实的奖励基于六方体增强。
> 效果：基于六方体数量提供幂次加成。

**Aethereal Augmentations（缥缈增幅）**
> 星力以大幅降低的比率增强星系之力生成。
> 效果：基于星力提供星系之力生成的幂次加成。

**Timeless Transcension（无时超升）**
> 第九${player.universes.current === 2 ? "正物质" : "反物质"}维度基于时钟速度增强。
> 效果：基于时钟速度提供倍率加成。

